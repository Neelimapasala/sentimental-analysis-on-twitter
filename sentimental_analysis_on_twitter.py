def predict_sentiment(text):
    cleaned   = preprocessor.clean(text)
    tfidf_vec = tfidf.transform([cleaned])
    ml_pred   = le.inverse_transform(results[best_ml]['model'].predict(tfidf_vec))[0]

    seq     = pad_sequences(keras_tok.texts_to_sequences([cleaned]),
                             maxlen=MAX_LEN, padding='post')
    probs   = lstm_model.predict(seq, verbose=0)[0]
    lstm_pred   = le.inverse_transform([np.argmax(probs)])[0]
    confidence  = probs[np.argmax(probs)]

    vader  = sia.polarity_scores(text)
    tb     = TextBlob(text).sentiment

    print("\n" + "="*60)
    print(f"📝 Text: {text[:80]}")
    print("="*60)
    print(f"🤖 ML  ({best_ml}): {ml_pred.upper()}")
    print(f"🧠 LSTM (BiLSTM)  : {lstm_pred.upper()}  (conf: {confidence*100:.1f}%)")
    print(f"\n📊 Class Probabilities:")
    for cls, prob in zip(le.classes_, probs):
        bar = '█' * int(prob * 20)
        print(f"   {cls:10s}: {bar:<20} {prob*100:.1f}%")
    print(f"\n🔍 VADER  — pos:{vader['pos']:.2f} neg:{vader['neg']:.2f} compound:{vader['compound']:.2f}")
    print(f"📌 TextBlob — polarity:{tb.polarity:.2f} subjectivity:{tb.subjectivity:.2f}")

