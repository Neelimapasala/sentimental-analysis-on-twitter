VOCAB_SIZE    = 5000
MAX_LEN       = 50
EMBEDDING_DIM = 64
NUM_CLASSES   = len(le.classes_)

keras_tok = Tokenizer(num_words=VOCAB_SIZE, oov_token='<OOV>')
keras_tok.fit_on_texts(X_train)

X_tr_seq = pad_sequences(keras_tok.texts_to_sequences(X_train),
                          maxlen=MAX_LEN, padding='post')
X_te_seq = pad_sequences(keras_tok.texts_to_sequences(X_test),
                          maxlen=MAX_LEN, padding='post')

y_tr_cat = tf.keras.utils.to_categorical(y_train, NUM_CLASSES)
y_te_cat = tf.keras.utils.to_categorical(y_test, NUM_CLASSES)

lstm_model = Sequential([
    Embedding(VOCAB_SIZE, EMBEDDING_DIM, input_length=MAX_LEN),
    Bidirectional(LSTM(64, return_sequences=True, dropout=0.3)),
    Bidirectional(LSTM(32, dropout=0.2)),
    Dense(64, activation='relu'),
    Dropout(0.4),
    Dense(32, activation='relu'),
    Dense(NUM_CLASSES, activation='softmax')
])
lstm_model.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])
lstm_model.summary()

history = lstm_model.fit(
    X_tr_seq, y_tr_cat,
    epochs=30, batch_size=8, validation_split=0.2,
    callbacks=[EarlyStopping(patience=5, restore_best_weights=True)],
    verbose=1
)

lstm_loss, lstm_acc = lstm_model.evaluate(X_te_seq, y_te_cat, verbose=0)
